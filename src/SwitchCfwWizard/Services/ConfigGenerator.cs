    // ── Ultrahand ───────────────────────────────────────────────
    private void WriteUltrahandConfig(
        WizardOptions options,
        string outRoot,
        string header,
        ConfigGenerationResult result,
        CancellationToken cancellationToken)
    {
        var loc = Localization.LocalizationService.Instance;
        var definition = ComponentCatalog.Get(ComponentKind.Ultrahand);

        var raw = Option(options, definition, "key_combo");
        var combo = ComponentCatalog.NormalizeKeyCombo(raw);

        if (combo is null)
        {
            // settings.json 是可以手改的，组合键写坏了会让热键失效，这里兜回官方默认值
            _log.Warn(string.Format(loc["Log.InvalidKeyCombo"], raw, ComponentCatalog.DefaultKeyCombo));
            combo = ComponentCatalog.DefaultKeyCombo;
        }

        var ini = new IniDocument();
        ini.HeaderComment("; " + header);
        ini.HeaderComment("; 参考：https://github.com/ppkantorski/Ultrahand-Overlay");
        ini.Comment("ultrahand", "呼出 Ultrahand 的组合键（用 + 连接，2–4 个按键）");
        ini.Set("ultrahand", "key_combo", combo);

        // [ultrahand] default_lang —— Ultrahand 的界面语言。
        //
        // 上游拿它拼 config/ultrahand/lang/<代码>.json；文件不存在时该语言在 Ultrahand 自己的
        // 设置里会被**跳过**，于是「配置说中文、卡上没有中文包」会静默退回内置英文。
        // 这里只管一件事：写进去的**一定**是 14 个合法代码之一 —— 哨兵与损坏值都不许漏到 ini。
        // 「指向的语言包到底在不在产物里」交给 OutputValidator（Check.Warn.DefaultLangNoLangFile），
        // 两处判据同源，不会各写一套。
        var langRaw = Option(options, definition, "default_lang").Trim();
        var defaultLang = ComponentCatalog.ResolveUltrahandDefaultLang(langRaw, options.Language);

        // 只有「填了个东西、但那东西不是合法代码」才算损坏 —— 哨兵与空值是正常输入。
        // 判据用 IsKnownUltrahandLanguage 而不是「解析结果与原值不同」：后者会把大小写差异
        // （用户手写 ZH-CN）也算成非法，凭空报一条警告。
        var isAuto = langRaw.Length == 0
                     || string.Equals(langRaw, ComponentCatalog.AutoLanguageValue, StringComparison.OrdinalIgnoreCase);

        if (!isAuto && !ComponentCatalog.IsKnownUltrahandLanguage(langRaw))
        {
            // settings.json 是可以手改的；静默换成另一个语言的话，用户会以为改生效了
            _log.Warn(string.Format(loc["Log.InvalidDefaultLang"], langRaw, defaultLang));
        }

        ini.Comment("ultrahand", "Ultrahand 界面语言：加载 config/ultrahand/lang/<代码>.json 里对应的那一份。");
        ini.Set("ultrahand", "default_lang", defaultLang);

        // [memory] 段：可选的自定义 Overlay 内存档位。
        //
        // 语义容易误会，这里说清楚：它**不会**直接把堆改成这个大小，而是让 Ultrahand
        // 「Overlay 内存」滑条多出第 4 档（原本固定 4 / 6 / 8 MB），用户还要在
        // Ultrahand 里手动选一次。上游 source/main.cpp 的校验是「纯数字 && >8 && 偶数」，
        // 不满足就整条忽略，所以这里必须严格照抄规则，别让非法值悄悄写进去。
        var memoryRaw = Option(options, definition, "custom_overlay_memory_MB");
        var customMemoryMb = NormalizeOverlayMemory(memoryRaw);

        if (customMemoryMb is null)
        {
            if (!string.IsNullOrWhiteSpace(memoryRaw))
            {
                _log.Warn(string.Format(loc["Log.InvalidOverlayMemory"], memoryRaw));
            }
        }
        else
        {
            ini.Comment("memory", "自定义 Overlay 内存档位（MB）。Ultrahand 的 Overlay 内存滑条会多出这一档，");
            ini.Comment("memory", "需在 Ultrahand 内手动选中才生效。仅接受大于 8 的偶数。");
            ini.Set("memory", "custom_overlay_memory_MB", customMemoryMb);
        }

        // 只写 Ultrahand 自己的这份。Ultrahand 首次启动时会自动把组合键镜像到
        // /config/tesla/config.ini（源码 copyTeslaKeyComboToUltrahand），
        // 我们没必要同时维护两份，反而容易写歪。

        WriteFile(
            Path.Combine(outRoot, "config", "ultrahand", "config.ini"),
            ini.Render(),
            result,
            cancellationToken);

        // config/ovl-sysmodules/config.ini —— ovl-sysmodules overlay 自己的开关。
        //
        // 它是 Ultrahand 生态里的一个 overlay，但配置文件**独立**于 config/ultrahand/config.ini，
        // 少了这份 overlay 里那几个开关就会用内置默认值，用户在向导里选的等于白选。
        var sysmodulesOptions = definition.Options
            .Where(o => string.Equals(
                o.TargetFile,
                "config/ovl-sysmodules/config.ini",
                StringComparison.OrdinalIgnoreCase))
            .ToList();

        if (sysmodulesOptions.Count > 0)
        {
            var sysmodules = new IniDocument();
            sysmodules.HeaderComment("; " + header);
            sysmodules.HeaderComment("; 参考：https://github.com/ppkantorski/ovl-sysmodules");

            foreach (var option in sysmodulesOptions)
            {
                sysmodules.Set(
                    option.Section ?? "ovl-sysmodules",
                    option.Key,
                    Option(options, definition, option.Key));
            }

            WriteFile(
                Path.Combine(outRoot, "config", "ovl-sysmodules", "config.ini"),
                sysmodules.Render(),
                result,
                cancellationToken);
        }
    }

    // ── payload 文件 ────────────────────────────────────────────
    /// <summary>
    /// 把暂存好的 payload 合并进 out/。
    ///
    /// payload 是**散装下载**的（Atmosphere 的 <c>fusee.bin</c>、Hekate 的
    /// <c>hekate_ctcaer_*.bin</c>），不在解压目录里，所以走单独一份暂存
    /// （<see cref="AppPaths.ComponentPayloadRoot"/>）。
    ///
    /// 落点在下载阶段就由 <c>AssetPick.Targets</c> 摆好了，暂存目录已经是「相对 out 根目录」
    /// 的结构，所以这里只做一次整棵合并，**不需要再认识任何具体文件名**。
    /// 以前是「把各组件下载目录顶层的 <c>*.bin</c> 一律平铺到 out 根目录」——
    /// 于是 fusee.bin 少了 <c>bootloader/payloads/</c> 这一层、hekate payload 也没了
    /// <c>payload.bin</c> / <c>bootloader/update.bin</c> 这两个名字。
    ///
    /// 独立于 <see cref="MergeComponentFiles"/>：两个开关各管各的，
    /// 用户可以只要 payload 不要组件本体（或反过来）。
    /// </summary>
    private void MergePayloads(
        WizardOptions options,
        string outRoot,
        ConfigGenerationResult result,
        CancellationToken cancellationToken)
    {
        foreach (var definition in ComponentCatalog.All)
        {
            if (!options.IsSelected(definition.Kind))
            {
                continue;
            }

            var staged = AppPaths.ComponentPayloadRoot(FolderName(definition.Kind));
            if (!Directory.Exists(staged))
            {
                continue;
            }

            foreach (var relative in ArchiveExtractor.MergeDirectory(staged, outRoot, cancellationToken))
            {
                // PayloadFiles 统一用 '/' 分隔：它要参与日志展示和校验器的路径比对，
                // 而 WrittenFiles 是给 File.Exists(Path.Combine(...)) 用的，两者互不影响。
                var normalized = relative.Replace('\\', '/');
                if (!result.PayloadFiles.Contains(normalized, StringComparer.OrdinalIgnoreCase))
                {
                    result.PayloadFiles.Add(normalized);
                }

                result.AddProducedFile(relative);
            }
        }

        if (result.PayloadFiles.Count > 0)
        {
            _log.Info(string.Format(
                Localization.LocalizationService.Instance["Log.PayloadsMerged"],
                string.Join(", ", result.PayloadFiles)));
        }
    }

    // ── 组件文件合并 ────────────────────────────────────────────
    /// <summary>
    /// 把各组件的解压暂存目录整棵合并进 out/。
    ///
    /// 暂存目录（<see cref="AppPaths.ComponentUnpackedRoot"/>）在下载阶段就被摆成了
    /// 「相对 out 根目录」的结构，所以这里是**无脑整棵铺开** —— 不需要认识任何具体文件，
    /// 也不会多出 <c>sdout/</c>、<c>nx-ovlloader/</c> 这类外层目录。
    /// </summary>
    private int MergeComponentFiles(
        WizardOptions options,
        string outRoot,
        ConfigGenerationResult result,
        CancellationToken cancellationToken)
    {
        var total = 0;

        foreach (var definition in ComponentCatalog.All)
        {
            if (!options.IsSelected(definition.Kind))
            {
                continue;
            }

            var folder = FolderName(definition.Kind);
            var unpacked = AppPaths.ComponentUnpackedRoot(folder);

            // 解压目录不在 = 这个组件一个文件都合并不进来。这里**不报错**（本方法只管搬运），
            // 但必须把它记成 0，让 OutputValidator 能按组件逐个对账 ——
            // 只记总数的话，「四个组件缺了一个」会被另外三个的几十个文件盖过去。
            var merged = 0;
            if (Directory.Exists(unpacked))
            {
                foreach (var relative in ArchiveExtractor.MergeDirectory(unpacked, outRoot, cancellationToken))
                {
                    // 合并进来的组件本体也要进清单，否则：
                    //   · 下次换组件 / 换版本时旧文件永远清不掉，会被一起拷进 SD 卡
                    //   · 打包后的完整性校验只覆盖配置文件，给出虚假的「全部在包内」
                    result.AddProducedFile(relative);
                    merged++;
                }
            }

            result.MergedFilesByComponent[definition.Kind] = merged;
            total += merged;
        }

        return total;
    }

    public static string FolderName(ComponentKind kind) => kind switch
    {
        ComponentKind.Atmosphere => "Atmosphere",
        ComponentKind.Hekate => "Hekate",
        ComponentKind.Ultrahand => "Ultrahand",
        ComponentKind.SysPatch => "Sys-patch",
        _ => kind.ToString(),
    };

    // ── 辅助 ────────────────────────────────────────────────────
    private static string Option(WizardOptions options, ComponentDefinition definition, string key)
    {
        var optionDefinition = definition.Options.FirstOrDefault(o => o.Key == key);
        return options.Get(definition.Kind, key, optionDefinition?.DefaultValue ?? string.Empty);
    }

    /// <summary>
    /// 校验 Ultrahand 的 <c>custom_overlay_memory_MB</c>。
    ///
    /// 规则照抄上游 <c>source/main.cpp</c>：值必须**只含数字**，且解析后
    /// <c>&gt; 8 &amp;&amp; % 2 == 0</c>；否则 Ultrahand 会整条忽略。既然写进去也没用，
    /// 这里就返回 <c>null</c> 让调用方跳过，而不是产出一份「看起来配了、其实没生效」的文件。
    /// 空串表示「不设置」，同样返回 <c>null</c>。
    /// </summary>
    private static string? NormalizeOverlayMemory(string? raw)
    {
        if (string.IsNullOrWhiteSpace(raw))
        {
            return null;
        }

        var text = raw.Trim();

        // 上游逐字符判断 '0'..'9'，负数、小数、正号都会让它作废
        if (!text.All(c => c is >= '0' and <= '9'))
        {
            return null;
        }

        if (!int.TryParse(text, out var megabytes))
        {
            return null;
        }

        return megabytes > 8 && megabytes % 2 == 0
            ? megabytes.ToString()
            : null;
    }

    private static string FormatTypedValue(string? prefix, string raw)
    {
        var value = raw ?? string.Empty;

        return prefix switch
        {
            "u8" => value is "1" or "true" or "True" ? "u8!0x1" : "u8!0x0",
            "u16" => "u16!" + value,
            "u32" => "u32!" + value,
            "u64" => "u64!" + value,
            "str" or "string" => "str!" + value,
            _ => value,
        };
    }

    private void WriteFile(string path, string content, ConfigGenerationResult result, CancellationToken cancellationToken)
    {
        cancellationToken.ThrowIfCancellationRequested();

        var directory = Path.GetDirectoryName(path);
        if (!string.IsNullOrEmpty(directory))
        {
            AppPaths.EnsureDirectory(directory);
        }

        // ini / hosts 文件统一使用 CRLF，方便在 Windows 上直接用记事本查看
        var normalized = content.Replace("\r\n", "\n").Replace("\n", "\r\n");
        File.WriteAllText(path, normalized, new UTF8Encoding(encoderShouldEmitUTF8Identifier: false));

        var relative = Path.GetRelativePath(AppPaths.OutputRoot, path);
        result.AddConfigFile(relative);
        _log.Info(string.Format(Localization.LocalizationService.Instance["Log.ConfigWritten"], relative));
    }

    /// <summary>删除上一次运行生成的、本次不再生成的文件。</summary>
    private void CleanPreviousOutput(string outRoot, ConfigGenerationResult result)
    {
        var manifestPath = Path.Combine(outRoot, ManifestFileName);
        if (!File.Exists(manifestPath))
        {
            return;
        }

        try
        {
            var previous = System.Text.Json.JsonSerializer.Deserialize<List<string>>(File.ReadAllText(manifestPath));
            if (previous is null)
            {
                return;
            }

            var normalizedRoot = Path.GetFullPath(outRoot);
            var emptiedParents = new HashSet<string>(StringComparer.OrdinalIgnoreCase);

            foreach (var relative in previous)
            {
                var full = Path.GetFullPath(Path.Combine(outRoot, relative));
                if (!full.StartsWith(normalizedRoot, StringComparison.OrdinalIgnoreCase) || !File.Exists(full))
                {
                    continue;
                }

                File.Delete(full);

                var parent = Path.GetDirectoryName(full);
                if (!string.IsNullOrEmpty(parent))
                {
                    emptiedParents.Add(parent);
                }
            }

            PruneEmptyDirectories(emptiedParents, normalizedRoot);
        }
        catch (Exception ex) when (ex is IOException or System.Text.Json.JsonException or UnauthorizedAccessException)
        {
            _log.Warn("清理上一次生成的文件时出现问题：" + ex.Message);
        }
    }

    /// <summary>
    /// 删掉「因为这次清理才变空」的目录。
    ///
    /// 为什么需要：清单驱动的清理只删文件，空目录会留下来。旧版本把 sdout.zip 的内容铺到
    /// <c>out/sdout/</c>、nx-ovlloader 铺到 <c>out/nx-ovlloader/</c>，升级后文件虽然清掉了，
    /// 这两个空文件夹还杵在那儿 —— 用户看到的仍然是「多了不该有的文件夹」。
    ///
    /// 只碰**确实被清空**的那些目录，并且逐级向上直到遇到非空目录就停：
    /// 组件包里刻意带的空目录（比如 <c>switch/.packages/</c>）不在被清空的路径上，不受影响。
    /// </summary>
    private static void PruneEmptyDirectories(IEnumerable<string> candidates, string outRoot)
    {
        // 路径越长越深，从最深的开始删；删完父目录可能也空了，所以逐级向上
        foreach (var candidate in candidates.OrderByDescending(path => path.Length))
        {
            var current = candidate;

            while (!string.IsNullOrEmpty(current)
                   && !string.Equals(current, outRoot, StringComparison.OrdinalIgnoreCase)
                   && current.StartsWith(outRoot, StringComparison.OrdinalIgnoreCase)
                   && Directory.Exists(current)
                   && !Directory.EnumerateFileSystemEntries(current).Any())
            {
                Directory.Delete(current);
                current = Path.GetDirectoryName(current);
            }
        }
    }

    private void WriteManifest(string outRoot, ConfigGenerationResult result)
    {
        try
        {
            var manifestPath = Path.Combine(outRoot, ManifestFileName);
            File.WriteAllText(
                manifestPath,
                System.Text.Json.JsonSerializer.Serialize(result.WrittenFiles, new System.Text.Json.JsonSerializerOptions { WriteIndented = true }));
        }
        catch (IOException ex)
        {
            _log.Warn("写入清单文件失败：" + ex.Message);
        }
    }

