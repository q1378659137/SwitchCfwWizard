internal sealed record BootEntry(string Title, List<string> Lines, string Caption);

/// <summary>极简 ini 构造器：支持注释、段、引导项与标题行。</summary>
internal sealed class IniDocument
{
    private readonly List<string> _header = new();
    private readonly List<Section> _sections = new();

    private sealed class Section
    {
        public Section(string name) => Name = name;

        public string Name { get; }

        public List<string> Lines { get; } = new();
    }

    public void HeaderComment(string line) => _header.Add(line);

    public void Comment(string section, string text)
        => GetSection(section).Lines.Add("; " + text);

    public void Set(string section, string key, string value)
        => GetSection(section).Lines.Add($"{key}={value}");

    public void Caption(string text) => GetSection(string.Empty).Lines.Add(text);

    public void BootEntry(string title, IEnumerable<string> lines)
    {
        var section = GetSection(title);
        section.Lines.AddRange(lines);
    }

    /// <summary>覆盖已写入的键值（用于 autoboot 索引回退）。</summary>
    public void OverrideKey(string section, string key, string value)
    {
        var target = GetSection(section);
        for (var i = 0; i < target.Lines.Count; i++)
        {
            if (target.Lines[i].StartsWith(key + "=", StringComparison.OrdinalIgnoreCase))
            {
                target.Lines[i] = $"{key}={value}";
                return;
            }
        }

        target.Lines.Add($"{key}={value}");
    }

    public string Render()
    {
        var builder = new StringBuilder();

        foreach (var line in _header)
        {
            builder.AppendLine(line);
        }

        foreach (var section in _sections)
        {
            builder.AppendLine();
            if (!string.IsNullOrEmpty(section.Name))
            {
                builder.AppendLine($"[{section.Name}]");
            }

            foreach (var line in section.Lines)
            {
                builder.AppendLine(line);
            }
        }

        return builder.ToString();
    }

    private Section GetSection(string name)
    {
        var section = _sections.FirstOrDefault(s => string.Equals(s.Name, name, StringComparison.Ordinal));
        if (section is null)
        {
            section = new Section(name);
            _sections.Add(section);
        }

        return section;
    }
}
